/**
 * 新建角色卡对话框（F11）。
 *
 * 两项输入：角色名（显示用，且写入 JSON 的 meta.name）与角色卡 ID（稳定标识）。
 *
 * 设计上两个要点：
 *
 * 1. **ID 留空就自动生成，并把生成值当场显示出来**
 *    （需求原文「生成值在对话框中明示给用户」）。因为用户之后找卡、排查冲突
 *    唯一的稳定线索就是这个 ID，不能悄悄生成完就藏起来。
 *
 * 2. **重复 ID 只提示、不阻断**
 *    F11.2 说「重复打开同 ID 的卡需提示该 ID 已打开」。提示放在输入框下方，
 *    用户看清楚后仍可以确认 —— 有时确实想并排比较同一张卡的两个版本，
 *    直接禁掉确认按钮会让人以为程序坏了。
 */

import {
  composeCardId,
  findDuplicateCardId,
  randomCardIdSuffix,
  validateCardId,
} from '../session/card-id.ts';

function el<K extends keyof HTMLElementTagNameMap>(
  tag: K,
  className?: string,
  text?: string,
): HTMLElementTagNameMap[K] {
  const node = document.createElement(tag);
  if (className) node.className = className;
  if (text !== undefined) node.textContent = text;
  return node;
}

export interface NewCardRequest {
  name: string;
  cardId: string;
}

export interface NewCardDialogOptions {
  /** 当前已打开的 ID 列表，用于检测重复 */
  openIds: readonly string[];
}

export class NewCardDialog {
  private readonly overlay: HTMLDivElement;
  private readonly nameInput: HTMLInputElement;
  private readonly idInput: HTMLInputElement;
  private readonly nameError: HTMLElement;
  private readonly idError: HTMLElement;
  private readonly idHint: HTMLElement;
  private readonly createButton: HTMLButtonElement;
  private readonly cancelButton: HTMLButtonElement;

  /** ID 是否由系统自动生成（用户没动过就跟着名字走） */
  private idAutoGenerated = true;
  /** 本次打开时的已占用 ID */
  private openIds: readonly string[] = [];
  /**
   * 本次打开期间固定的 ID 后缀。
   *
   * 必须固定：用户在名字框里打字时 slug 会变，但后缀每敲一个字都换的话，
   * 界面上展示的 ID 就成了一个"随手就变"的值 —— 那就没有"明示给用户"的意义了。
   */
  private suffix = randomCardIdSuffix();
  private resolver: ((value: NewCardRequest | null) => void) | null = null;

  constructor() {
    this.overlay = el('div', 'modal-overlay');
    this.overlay.hidden = true;
    this.overlay.setAttribute('role', 'dialog');
    this.overlay.setAttribute('aria-modal', 'true');

    const panel = el('div', 'modal new-card-modal');
    const head = el('div', 'modal-head');
    const title = el('h2', 'modal-title', '新建角色卡');
    const close = el('button', 'icon-btn', '×');
    close.type = 'button';
    close.addEventListener('click', () => this.finish(null));
    head.append(title, close);

    const body = el('div', 'modal-body');

    // ── 角色名 ──────────────────────────────────────────
    const nameField = el('label', 'field');
    nameField.append(el('span', 'field-label', '角色名'));
    this.nameInput = el('input', 'input');
    this.nameInput.type = 'text';
    this.nameInput.placeholder = '例：林晚照';
    this.nameInput.maxLength = 120;
    this.nameInput.addEventListener('input', () => {
      // ID 还没被用户手动改过时，跟着名字同步生成 —— 省去用户自己想 ID
      if (this.idAutoGenerated) {
        this.idInput.value = composeCardId(this.nameInput.value, this.suffix);
        this.idHint.hidden = false;
      }
      this.validate();
    });
    nameField.append(this.nameInput);
    this.nameError = el('span', 'field-hint bad');
    this.nameError.hidden = true;
    nameField.append(this.nameError);

    // ── 角色卡 ID ───────────────────────────────────────
    const idField = el('label', 'field');
    idField.append(el('span', 'field-label', '角色卡 ID'));
    this.idInput = el('input', 'input mono');
    this.idInput.type = 'text';
    this.idInput.placeholder = '留空则自动生成';
    this.idInput.addEventListener('input', () => {
      // 一旦用户手动改过，就停止自动跟随（否则会被覆盖，输入体验很差）
      this.idAutoGenerated = this.idInput.value.trim() === '';
      this.idHint.hidden = !this.idAutoGenerated;
      this.validate();
    });
    idField.append(this.idInput);
    this.idHint = el('span', 'field-hint', '留空则按角色名自动生成，生成值会显示在这里。');
    idField.append(this.idHint);
    this.idError = el('span', 'field-hint bad');
    this.idError.hidden = true;
    idField.append(this.idError);
    idField.append(
      el(
        'span',
        'field-hint',
        '用于服务端识别这张卡：同一个 ID 上传会追加版本，换 ID 等于换一张卡。创建后不能修改。',
      ),
    );

    body.append(nameField, idField);

    // ── 底部 ────────────────────────────────────────────
    const foot = el('div', 'modal-foot');
    this.cancelButton = el('button', 'btn', '取消');
    this.cancelButton.type = 'button';
    this.cancelButton.addEventListener('click', () => this.finish(null));
    this.createButton = el('button', 'btn primary', '创建');
    this.createButton.type = 'button';
    this.createButton.addEventListener('click', () => this.submit());
    foot.append(this.cancelButton, this.createButton);

    panel.append(head, body, foot);
    this.overlay.append(panel);

    this.overlay.addEventListener('click', (event) => {
      if (event.target === this.overlay) this.finish(null);
    });
    document.addEventListener('keydown', (event) => {
      if (this.overlay.hidden) return;
      if (event.key === 'Escape') {
        event.preventDefault();
        this.finish(null);
      }
      if (event.key === 'Enter' && event.target !== this.createButton) {
        event.preventDefault();
        this.submit();
      }
    });

    document.body.append(this.overlay);
  }

  /**
   * 打开对话框，等用户确认。
   * 返回 null 表示取消。
   */
  open(options: NewCardDialogOptions): Promise<NewCardRequest | null> {
    this.openIds = options.openIds;
    this.overlay.hidden = false;

    this.nameInput.value = '';
    this.idAutoGenerated = true;
    // 每次打开换一个新后缀（避免连续新建两张同名卡得到同一个 ID），
    // 但本次打开期间保持不变。
    this.suffix = randomCardIdSuffix();
    // 预置一个 ID：用户直接点「创建」也能得到合法且唯一的 ID
    this.idInput.value = composeCardId('', this.suffix);
    this.idHint.hidden = false;
    this.nameError.hidden = true;
    this.idError.hidden = true;

    this.validate();
    // 焦点放角色名：这是用户第一件想填的事
    this.nameInput.focus();

    return new Promise((resolve) => {
      this.resolver = resolve;
    });
  }

  /** 供端到端测试/截图入口调用：填表并提交 */
  fillAndSubmit(request: Partial<NewCardRequest>): void {
    if (request.name !== undefined) {
      this.nameInput.value = request.name;
      this.nameInput.dispatchEvent(new Event('input', { bubbles: true }));
    }
    if (request.cardId !== undefined) {
      this.idInput.value = request.cardId;
      this.idInput.dispatchEvent(new Event('input', { bubbles: true }));
    }
    this.submit();
  }

  get visible(): boolean {
    return !this.overlay.hidden;
  }

  private finish(value: NewCardRequest | null): void {
    this.overlay.hidden = true;
    const resolve = this.resolver;
    this.resolver = null;
    resolve?.(value);
  }

  /**
   * 校验并渲染错误。
   *
   * 角色名允许为空吗？**允许**。F10.2 明确写了「清空名称：允许（审计按既有语义报
   * 角色名不能为空）」，新建时同理 —— 强制非空会让"先建卡再慢慢起名"这个
   * 很自然的流程走不通，而审计面板本来就会提示必填。
   */
  private validate(): boolean {
    const name = this.nameInput.value.trim();
    const idRaw = this.idInput.value.trim();
    const id = idRaw === '' ? composeCardId(name, this.suffix) : idRaw;

    const idCheck = validateCardId(id);
    if (!idCheck.ok) {
      this.idError.textContent = idCheck.message ?? 'ID 不合法';
      this.idError.hidden = false;
    } else {
      const duplicate = findDuplicateCardId(idCheck.id, this.openIds);
      if (duplicate !== null) {
        this.idError.textContent = `该 ID 已打开（${duplicate}）。继续创建会得到两张同 ID 的卡。`;
        this.idError.hidden = false;
      } else {
        this.idError.hidden = true;
      }
    }

    // 名字只做长度层面的软校验，不阻断
    this.nameError.hidden = true;

    // 「创建」始终可点：ID 非法时也允许点，点了会在下方给出具体原因，
    // 比一个灰掉且不说原因的按钮好用。
    this.createButton.disabled = false;
    return idCheck.ok;
  }

  private submit(): void {
    const name = this.nameInput.value.trim();
    const idRaw = this.idInput.value.trim();
    const id = idRaw === '' ? composeCardId(name, this.suffix) : idRaw;

    const idCheck = validateCardId(id);
    if (!idCheck.ok) {
      this.validate();
      this.idInput.focus();
      return;
    }

    this.finish({ name, cardId: idCheck.id });
  }
}
