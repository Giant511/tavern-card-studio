/**
 * 服务宿主（WinSW）配置的唯一生成源。
 *
 * 为什么单独成文件：绿色包与 MSI 各需要一份 XML，两者只应在**数据目录**上不同，
 * 其余语义（崩溃重启、日志滚动、停止超时）必须一致 —— 否则同一份服务在两种部署
 * 下行为不同，排障时极易误判。抽出来之后：
 *   · scripts/pack-server.mjs  用它生成 release/server/tcs-service-host.xml
 *   · test/service-host.test.mjs 断言它与 installer/ServiceHost.xml 关键字段一致
 * 靠人"记得同步"必然漂移，所以用测试钉住。
 */

/**
 * 绿色包用的 WinSW 配置。
 *
 * 与 installer/ServiceHost.xml 的唯一区别：数据目录是 `%BASE%\data`（跟包走），
 * 而不是 MSI 的 `C:\ProgramData\TavernCardStudio`。
 *
 * @returns {string} 完整 XML 文本（结尾带换行）
 */
export function buildBundleServiceHostXml() {
  // WinSW 会把 %BASE% 替换成宿主 exe 所在目录，因此不需要拼绝对路径。
  return `<?xml version="1.0" encoding="UTF-8"?>
<!--
  Generated by scripts/pack-server.mjs — do not edit by hand.
  Source of truth for the MSI variant: installer/ServiceHost.xml
  Data directory differs on purpose: a portable bundle keeps its data next to
  itself (%BASE%\\data) instead of C:\\ProgramData.
-->
<service>
  <id>TavernCardStudioServer</id>
  <name>Tavern Card Studio Server</name>
  <description>Tavern Card Studio: character card storage, audit and git-based version control.</description>

  <executable>%BASE%\\node.exe</executable>
  <arguments>"%BASE%\\app\\server\\dist\\index.js" serve --config "%BASE%\\data\\config.json" --rules-dir "%BASE%\\app\\rules"</arguments>
  <workingdirectory>%BASE%</workingdirectory>

  <!-- Plain Automatic: <delayedAutoStart> is not a standalone element in WinSW v2. -->
  <startmode>Automatic</startmode>

  <logpath>%BASE%\\data\\logs</logpath>
  <log mode="roll-by-size">
    <sizeThreshold>10240</sizeThreshold>
    <keepFiles>4</keepFiles>
  </log>

  <onfailure action="restart" delay="10 sec" />
  <onfailure action="restart" delay="30 sec" />
  <resetfailure>1 hour</resetfailure>

  <stoptimeout>20 sec</stoptimeout>
  <stopparentprocessfirst>true</stopparentprocessfirst>
</service>
`;
}

/**
 * 两份配置必须一致的字段。
 *
 * 只比对"决定运行语义"的项，不比对数据目录与日志路径 —— 那两个是有意不同的
 * （MSI 用 ProgramData，绿色包用 %BASE%\data）。
 *
 * @returns {Array<{ label: string, pattern: RegExp }>}
 */
export function sharedServiceHostFields() {
  return [
    { label: 'service id', pattern: /<id>\s*TavernCardStudioServer\s*<\/id>/ },
    { label: '启动类型', pattern: /<startmode>\s*Automatic\s*<\/startmode>/ },
    { label: '可执行文件是宿主同目录的 node.exe', pattern: /<executable>\s*%BASE%\\node\.exe\s*<\/executable>/ },
    { label: '入口是 app/server/dist/index.js', pattern: /<arguments>[^<]*app\\server\\dist\\index\.js/ },
    { label: '规则目录', pattern: /--rules-dir\s+"%BASE%\\app\\rules"/ },
    { label: '工作目录', pattern: /<workingdirectory>\s*%BASE%\s*<\/workingdirectory>/ },
    { label: '日志按大小滚动', pattern: /<log mode="roll-by-size">/ },
    { label: '崩溃后重启（第一次 10 秒）', pattern: /<onfailure action="restart" delay="10 sec"\s*\/>/ },
    { label: '崩溃后重启（第二次 30 秒）', pattern: /<onfailure action="restart" delay="30 sec"\s*\/>/ },
    { label: '失败计数重置窗口', pattern: /<resetfailure>\s*1 hour\s*<\/resetfailure>/ },
    { label: '停止超时（给 supervisor 收尾时间）', pattern: /<stoptimeout>\s*20 sec\s*<\/stoptimeout>/ },
    { label: '先停父进程', pattern: /<stopparentprocessfirst>\s*true\s*<\/stopparentprocessfirst>/ },
  ];
}
