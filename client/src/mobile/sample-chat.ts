/**
 * 验收用对话快照（`?sample=1`）。
 *
 * ## 为什么需要它
 *
 * 移动端还没接上 ST（T15.3 主体未做），没有历史可以 `loadChat`。
 * 而这一轮用户报的第一个问题——"输入区悬浮在页面中部"——
 * **在空状态下看不出来**：空状态里消息区是一张居中的空状态卡，
 * 高度由卡片自己决定，输入区就算用了 `flex:0 0 auto` 也照样贴底。
 * 只有真的有十几条消息、列表能滚起来时，才能验证：
 *
 *   · 输入区是不是固定在 Tab 栏上方
 *   · 消息滚到最后一条时会不会被输入区盖住
 *   · 长消息（列表、引用、代码块）会不会把布局撑破
 *
 * 桌面端遇到同一问题时的做法是 `?sample=1`（`editor/app.ts:5344`），
 * 且 `scripts/capture-e2e-dumps.sh` 里每个需要"有内容的卡"的场景都显式带它。
 * 这里是同一口径，不是新发明。
 *
 * ## 为什么单独一个文件
 *
 * 这批文本必须**逐字**保留（Markdown 里有什么就渲染什么，
 * 改一个字就失去了"验证长消息"的意义），而 `main.ts` 是入口装配文件，
 * 把三十行样本混进去会让"这个文件在做什么"变得模糊。
 * 分开的另一个好处：`test/mobile-ui-fixes.test.mjs` 可以只对这个文件
 * 断言"样本仍覆盖这几种形态"，不必解析 `main.ts`。
 *
 * ## 它不会进正式界面
 *
 * 只有 URL 带 `?sample=1` 才会被 import 并调用（见 `main.ts` 的 `boot()`）。
 * 普通用户打开 App 走不到这里。但**样本文字本身仍受文案体检约束**：
 * 里面不许出现测试性措辞（`scripts/verify-ui-copy.mjs` 会扫这个文件）。
 */

